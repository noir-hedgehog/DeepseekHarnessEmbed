// Generates src/embedded-server-package.ts from server-package/ so the
// Obsidian plugin can install the DSH-side companion package self-contained.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkgDir = join(root, "server-package");
const files = ["package.json", "lib/index.js", "lib/client.js"];

const entries = files.map(
  (f) => `  ${JSON.stringify(f)}: ${JSON.stringify(readFileSync(join(pkgDir, f), "utf8"))},`,
);
const version = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8")).version;

const out = `// GENERATED by scripts/gen-embedded.mjs — do not edit by hand.
export const SERVER_PACKAGE_VERSION = ${JSON.stringify(version)};
export const SERVER_FILES: Record<string, string> = {
${entries.join("\n")}
};
`;

mkdirSync(join(root, "src"), { recursive: true });
writeFileSync(join(root, "src/embedded-server-package.ts"), out);
console.log(`embedded server package v${version} (${files.length} files)`);
